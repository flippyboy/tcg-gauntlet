// Build tooling. Writes src/version.ts from package.json (the `prebuild` step).
import { readFileSync, writeFileSync } from "node:fs";

const pkgUrl = new URL("../package.json", import.meta.url);
const { version } = JSON.parse(readFileSync(pkgUrl, "utf8")) as {
  version: string;
};
writeFileSync(
  new URL("../src/version.ts", import.meta.url),
  `// Generated by scripts/write-version.ts from package.json. Do not edit.\nexport const ENGINE_VERSION = ${JSON.stringify(version)};\n`,
);
